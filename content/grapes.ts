export const grapeBySlug = (slug: string) => grapes.find((g) => g.slug === slug);

/** Encontra a uva cadastrada a partir de um texto livre (ex.: "Shiraz", "cabernet"). */
export const matchGrape = (text?: string) => {
  if (!text) return undefined;
  const norm = (v: string) => v.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
  const t = norm(text);
  const aliases: Record<string, string[]> = {
    "cabernet-sauvignon": ["cabernet sauvignon"],
    "pinot-noir": ["pinot noir", "pinot nero", "spatburgunder"],
    syrah: ["syrah", "shiraz"],
    malbec: ["malbec"],
    tempranillo: ["tempranillo", "tinta roriz", "aragonez", "tinto fino"],
    sangiovese: ["sangiovese", "brunello", "chianti"],
    nebbiolo: ["nebbiolo", "barolo", "barbaresco"],
    carmenere: ["carmenere"],
    "sauvignon-blanc": ["sauvignon blanc", "fume blanc"],
    "chenin-blanc": ["chenin"],
    moscato: ["moscato", "moscatel", "muscat"],
    gewurztraminer: ["gewurz", "traminer"],
    merlot: ["merlot"],
    chardonnay: ["chardonnay"],
    riesling: ["riesling"],
  };
  return grapes.find((g) => (aliases[g.slug] ?? [norm(g.name)]).some((alias) => t.includes(alias)));
};
